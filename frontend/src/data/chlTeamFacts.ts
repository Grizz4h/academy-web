export function getChlTeamFacts(teamId: string): TeamFacts | null {
  const key = teamId.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '')
  return CHL_TEAM_FACTS[key] || null
}

/** Try to find facts by iterating normalised name variants. */
export function getChlTeamFactsByName(name: string): TeamFacts | null {
  const norm = name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '')
  if (CHL_TEAM_FACTS[norm]) return CHL_TEAM_FACTS[norm]
  // Partial match fallback
  for (const [key, facts] of Object.entries(CHL_TEAM_FACTS)) {
    if (facts.fullName.toLowerCase() === name.toLowerCase()) return facts
    if (key.includes(norm) || norm.includes(key)) return facts
  }
  return null
}
